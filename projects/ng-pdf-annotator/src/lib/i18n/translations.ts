/** Mezcla profunda de un diccionario base con una sobrescritura parcial. */
export function mergeTranslations<T extends object>(base: T, override?: unknown): T {
  if (!override || typeof override !== 'object') return base;
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const [k, v] of Object.entries(override as Record<string, unknown>)) {
    const b = out[k];
    out[k] = v && typeof v === 'object' && b && typeof b === 'object' ? mergeTranslations(b as object, v) : v;
  }
  return out as T;
}

/** Sustituye `{param}` en un texto. */
export function interpolate(text: string, params: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`));
}
